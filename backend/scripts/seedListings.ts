/**
 * Loads the "Hostel, PG, Flat" browse page with real, sourced listings across 20 of the
 * country's biggest student/college cities — the same city set as seedPlaces.ts.
 *
 * Conventions, and why:
 *
 * 1. Every listing here is real and traceable to a public source page (see `source` on each
 *    entry — kept in this file as a comment/reference for verification, not written to the DB;
 *    the Listing schema has no field for it). Nothing is invented: `rent`, `deposit` and
 *    `contactPhone` are included only where the source page stated them explicitly, and are
 *    left out entirely otherwise rather than estimated — same reasoning as seedPlaces' rule for
 *    `rating`/`imageUrl`/`openingHours`. Verify before trusting: rents, availability and phone
 *    numbers for small PG/hostel operators change often and these were captured at one point in
 *    time, not from a live feed. The Listings admin editor is the place to correct anything
 *    that has moved on.
 * 2. `contactPhone` is only ever copied from a number the operator published on their own page
 *    specifically to receive inbound inquiries (their own site, or a listing they control on an
 *    aggregator) — never scraped from a gated "reveal number" control.
 * 3. `mapsLink` is a Google Maps *search* URL built from title + city, not the source URL —
 *    same approach as seedPlaces, since a search never 404s and always resolves to whatever's
 *    currently there.
 * 4. City names must match `lib/indianCities.ts` exactly, same requirement as seedPlaces.ts —
 *    `listListings` matches city with an anchored case-insensitive regex (listingService.ts:12).
 *
 * Idempotent — upserts by { city, title }. Re-running updates copy in place; it deliberately
 * does NOT touch `featured`, so anything an admin sets through the editor survives a re-seed.
 * Writes only to the Listing collection, which makes it safe against a live deployment.
 *
 * Usage: npm run seed:listings
 */
