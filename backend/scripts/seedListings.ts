async function main() {
  await mongoose.connect(process.env.MONGODB_URI as string);

  let created = 0;
  let updated = 0;

  for (const [city, listings] of Object.entries(CITY_LISTINGS)) {
    for (const { source: _source, ...seed } of listings) {
      const result = await Listing.updateOne(
        { city, title: seed.title },
        {
          $set: {
            type: seed.type,
            city,
            title: seed.title,
            address: seed.address,
            rent: seed.rent ?? null,
            deposit: seed.deposit ?? null,
            contactName: seed.contactName ?? "",
            contactPhone: seed.contactPhone ?? "",
            mapsLink: maps(seed.title, city),
            description: seed.description,
          },
        },
        { upsert: true },
      );
      if (result.upsertedCount > 0) created++;
      else updated++;
    }
  }

  console.log(`Listings seeded: ${created} created, ${updated} updated.`);
  await mongoose.disconnect();
}

main();
